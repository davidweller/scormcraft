/**
 * Copy every course and media item from the web database (Neon) into the
 * desktop app's local database, downloading files from Vercel Blob into local
 * storage and pointing the copied records at them.
 *
 * Neon and Blob are only read, never changed. Records already in the local
 * database (same id) are skipped, so the script can be re-run safely.
 *
 *   npx tsx scripts/neon-to-local.ts --dry-run    # counts only
 *   npx tsx scripts/neon-to-local.ts              # copy into %APPDATA%/SCORMcraft/data
 *   npx tsx scripts/neon-to-local.ts --target <data dir>
 *
 * Close SCORMcraft first: SQLite allows one writer.
 * Reads the Neon url from DATABASE_URL (.env).
 */
import "dotenv/config";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { PrismaClient as PgClient } from "@prisma/client";
import { applyDesktopMigrations } from "../src/lib/desktop/migrate";

const args = process.argv.slice(2);
const DRY_RUN = args.includes("--dry-run");
const targetArg = args.indexOf("--target");
const appData = process.env.APPDATA || join(process.env.HOME || ".", "AppData", "Roaming");
const DATA_DIR = resolve(targetArg >= 0 ? args[targetArg + 1] : join(appData, "SCORMcraft", "data"));
const DB_PATH = join(DATA_DIR, "scormcraft.db");
const FILES_DIR = join(DATA_DIR, "files");

const BLOB_URL = /https:\/\/[a-z0-9]+\.public\.blob\.vercel-storage\.com\/[^\s"'<>)\\]+/gi;

const neonUrl = process.env.DATABASE_URL ?? "";
if (!/^postgres(ql)?:\/\//.test(neonUrl)) {
  console.error("DATABASE_URL must be the Neon postgres url (from .env).");
  process.exit(1);
}

function localPathFor(url: string): string {
  const u = new URL(url);
  return u.pathname
    .replace(/^\/+/, "")
    .split("/")
    .map((s) => decodeURIComponent(s))
    .join("/");
}

function localUrlFor(pathname: string): string {
  return "/files/" + pathname.split("/").map(encodeURIComponent).join("/");
}

/** Rewrite every Blob url inside a JSON-able value; collects the urls to fetch. */
function rewrite<T>(value: T, found: Set<string>): T {
  if (value === null || value === undefined) return value;
  const json = JSON.stringify(value).replace(BLOB_URL, (m) => {
    found.add(m);
    return localUrlFor(localPathFor(m));
  });
  return JSON.parse(json) as T;
}

async function download(url: string): Promise<boolean> {
  const dest = join(FILES_DIR, ...localPathFor(url).split("/"));
  if (!resolve(dest).startsWith(resolve(FILES_DIR))) return false;
  if (existsSync(dest)) return true;
  const res = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!res.ok) {
    console.warn(`  ! ${res.status} ${url}`);
    return false;
  }
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
  return true;
}

async function main() {
  // Neon suspends idle computes; give the first connection time to wake one.
  const url = new URL(neonUrl);
  if (!url.searchParams.has("connect_timeout")) url.searchParams.set("connect_timeout", "60");
  const neon = new PgClient({ datasources: { db: { url: url.toString() } } });

  const [courses, modules, lessons, pages, blocks, media] = await Promise.all([
    neon.course.findMany(),
    neon.module.findMany(),
    neon.lesson.findMany(),
    neon.page.findMany(),
    neon.block.findMany(),
    neon.media.findMany(),
  ]);
  await neon.$disconnect();

  const found = new Set<string>();
  const cCourses = courses.map((c) => rewrite(c, found));
  const cPages = pages.map((p) => rewrite(p, found));
  const cBlocks = blocks.map((b) => rewrite(b, found));
  const cMedia = media.map((m) => rewrite(m, found));

  console.log(
    `Neon: ${courses.length} courses, ${modules.length} modules, ${lessons.length} lessons, ` +
      `${pages.length} pages, ${blocks.length} blocks, ${media.length} media; ${found.size} Blob files.`
  );
  console.log(`Target: ${DATA_DIR}`);
  if (DRY_RUN) {
    console.log("Dry run: nothing written.");
    return;
  }

  mkdirSync(FILES_DIR, { recursive: true });
  let ok = 0;
  let failed = 0;
  for (const url of found) {
    try {
      if (await download(url)) ok++;
      else failed++;
    } catch (e) {
      failed++;
      console.warn(`  ! ${url}: ${e instanceof Error ? e.message : e}`);
    }
  }
  console.log(`Files: ${ok} downloaded or already present, ${failed} failed.`);

  // The SQLite client is generated by `npm run db:generate` / desktop builds.
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { PrismaClient: SqliteClient, Prisma: SqlitePrisma } = require(
    join(process.cwd(), "src", "generated", "prisma-sqlite")
  ) as { PrismaClient: typeof PgClient; Prisma: typeof import("@prisma/client").Prisma };
  const local = new SqliteClient({ datasources: { db: { url: "file:" + DB_PATH.replace(/\\/g, "/") } } });
  await applyDesktopMigrations(join(process.cwd(), "prisma", "sqlite", "migrations"), local);

  const J = <T>(v: T) => (v === null ? SqlitePrisma.JsonNull : v) as never;
  const have = async (table: "course" | "module" | "lesson" | "page" | "block" | "media") =>
    new Set(
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      ((await (local as any)[table].findMany({ select: { id: true } })) as { id: string }[]).map((r) => r.id)
    );

  const existingCourses = await have("course");
  const newCourses = cCourses.filter((c) => !existingCourses.has(c.id));
  await local.course.createMany({
    data: newCourses.map((c) => ({
      ...c,
      brandConfig: J(c.brandConfig),
      settings: J(c.settings),
      ilos: J(c.ilos),
      assessmentPlan: J(c.assessmentPlan),
      interactionConfig: J(c.interactionConfig),
    })),
  });
  const existingModules = await have("module");
  await local.module.createMany({ data: modules.filter((m) => !existingModules.has(m.id)) });
  const existingLessons = await have("lesson");
  await local.lesson.createMany({ data: lessons.filter((l) => !existingLessons.has(l.id)) });
  const existingPages = await have("page");
  await local.page.createMany({
    data: cPages.filter((p) => !existingPages.has(p.id)).map((p) => ({ ...p, completionRules: J(p.completionRules) })),
  });
  const existingBlocks = await have("block");
  const newBlocks = cBlocks.filter((b) => !existingBlocks.has(b.id));
  for (let i = 0; i < newBlocks.length; i += 500) {
    await local.block.createMany({ data: newBlocks.slice(i, i + 500).map((b) => ({ ...b, data: b.data as never })) });
  }
  const existingMedia = await have("media");
  await local.media.createMany({ data: cMedia.filter((m) => !existingMedia.has(m.id)) });

  console.log(
    `Copied ${newCourses.length} new courses (${courses.length - newCourses.length} already there), ` +
      `${newBlocks.length} blocks, ${cMedia.length - existingMedia.size} media.`
  );
  await local.$disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
